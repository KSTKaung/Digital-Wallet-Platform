// Generates src/api/schema.d.ts from the backend's OpenAPI document (documentations/08 §4D, D9).
//
// Usage (from frontend/): npm run api:types
// The backend must run with the `local` profile, which serves /v3/api-docs. Set OPENAPI_URL to read
// another URL or a local JSON/YAML file. Written in Node so it works the same under sh and cmd.
import { writeFile } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const DEFAULT_URL = 'http://127.0.0.1:8080/v3/api-docs';
const OUTPUT = new URL('../src/api/schema.d.ts', import.meta.url);

function resolveSource(value) {
  try {
    const url = new URL(value);
    if (['http:', 'https:', 'file:'].includes(url.protocol)) return url;
  } catch {
    // Not a URL: treat it as a file path below.
  }
  return pathToFileURL(value);
}

const source = resolveSource(process.env.OPENAPI_URL || DEFAULT_URL);

const header = `/**
 * GENERATED FILE - do not edit by hand.
 *
 * Generated by openapi-typescript from ${source.href}
 * (the backend's OpenAPI document, served in the \`local\` profile).
 * Regenerate from frontend/: npm run api:types (set OPENAPI_URL for another source).
 */

`;

try {
  const ast = await openapiTS(source);
  await writeFile(OUTPUT, header + astToString(ast), 'utf8');
  process.stdout.write(`Wrote ${fileURLToPath(OUTPUT)} from ${source.href}\n`);
} catch (error) {
  process.stderr.write(
    `Could not generate API types from ${source.href}: ${error instanceof Error ? error.message : String(error)}\n`,
  );
  process.exit(1);
}
