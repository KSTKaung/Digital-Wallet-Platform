// Generates src/api/schema.d.ts from the backend's OpenAPI document (documentations/08 §4D D9,
// §4E E2).
//
// Usage (from frontend/):
//   npm run api:types
//     Reads the committed document ../openapi/openapi.json (repo root). This is what CI runs before
//     `git diff --exit-code -- src/api/schema.d.ts`, so the committed types must equal its output.
//   OPENAPI_URL=http://127.0.0.1:8080/v3/api-docs npm run api:types
//     Local use only: reads a running backend (`local` profile, which serves /v3/api-docs), or any
//     other URL or JSON/YAML file path. Do not commit that output unless openapi/openapi.json was
//     regenerated from the same backend.
//
// The output is deterministic: a fixed header (no timestamp, no source path) followed by the
// openapi-typescript output, so the same document always gives the same file. Written in Node so
// it works the same under sh and cmd.
import { writeFile } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const COMMITTED_DOCUMENT = new URL('../../openapi/openapi.json', import.meta.url);
const OUTPUT = new URL('../src/api/schema.d.ts', import.meta.url);

function resolveSource(value) {
  try {
    const url = new URL(value);
    if (['http:', 'https:', 'file:'].includes(url.protocol)) return url;
  } catch {
    // Not a URL: treat it as a file path below.
  }
  return pathToFileURL(value);
}

const override = process.env.OPENAPI_URL;
const source = override ? resolveSource(override) : COMMITTED_DOCUMENT;
const sourceLabel = override ? source.href : 'openapi/openapi.json';

const header = `/**
 * GENERATED FILE - do not edit by hand.
 *
 * Generated by openapi-typescript from openapi/openapi.json (the committed backend OpenAPI
 * document). Regenerate from frontend/: npm run api:types. CI fails when this file differs from
 * the output for the committed document.
 */

`;

try {
  const ast = await openapiTS(source);
  await writeFile(OUTPUT, header + astToString(ast), 'utf8');
  process.stdout.write(`Wrote ${fileURLToPath(OUTPUT)} from ${sourceLabel}\n`);
} catch (error) {
  process.stderr.write(
    `Could not generate API types from ${sourceLabel}: ${error instanceof Error ? error.message : String(error)}\n`,
  );
  process.exit(1);
}
